describe("what a run leaves for a person to read", () => {
  test("puts each lane's report where a local run writes it", (t) => {
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");

    // The container mirrors the checkout's layout under the mount, so the
    // copy back needs no mapping table and a reader of `/out` can see at once
    // where each file came from.
    mkdirSync(resolve(from, "apps/web/acceptance-report"), { recursive: true });
    mkdirSync(resolve(from, "apps/web/test-results/appearance-webkit"), {
      recursive: true,
    });
    writeFileSync(
      resolve(from, "apps/web/acceptance-report/appearance-webkit.json"),
      '{"suites":[]}',
    );
    writeFileSync(
      resolve(from, "apps/web/test-results/appearance-webkit/trace.zip"),
      "not really a zip",
    );

    const collected = collectArtefacts(from, ["appearance-webkit"], into);

    assert.ok(
      collected.some((path) =>
        path.endsWith("apps/web/acceptance-report/appearance-webkit.json"),
      ),
      collected.join(", "),
    );
    assert.ok(
      collected.some((path) => path.endsWith("trace.zip")),
      collected.join(", "),
    );
    assert.equal(
      readFileSync(
        resolve(into, "apps/web/acceptance-report/appearance-webkit.json"),
        "utf8",
      ),
      '{"suites":[]}',
    );
  });

  test("removes the lane's previous artefacts before laying down this run's", (t) => {
    // Two runs of the same lane left both failures side by side, and a lane
    // this run never ran kept its results from the run before. Nothing then
    // says which run a file came from — the hazard `acceptance-report`'s own
    // comment names, which is why the acceptance runner empties that directory
    // before its first lane.
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");
    const report = resolve(into, "apps/web/acceptance-report");
    const results = resolve(into, "apps/web/test-results");

    mkdirSync(report, { recursive: true });
    mkdirSync(resolve(results, "route-state-webkit"), { recursive: true });
    mkdirSync(resolve(results, "a-case-route-state-webkit"), {
      recursive: true,
    });
    mkdirSync(resolve(results, "a-case-appearance-chromium"), {
      recursive: true,
    });
    writeFileSync(resolve(report, "route-state-webkit.json"), "stale");
    writeFileSync(resolve(report, "appearance-chromium.json"), "another lane");
    writeFileSync(resolve(results, "a-case-route-state-webkit/trace.zip"), "x");
    writeFileSync(
      resolve(results, "a-case-appearance-chromium/trace.zip"),
      "y",
    );

    // Something for this run to put in the previous run's place: clearing
    // happens only when there is a replacement, so a mount the container never
    // filled leaves the earlier evidence alone.
    mkdirSync(resolve(from, "apps/web/acceptance-report"), { recursive: true });
    writeFileSync(
      resolve(from, "apps/web/acceptance-report/route-state-webkit.json"),
      "this run",
    );

    // Driven through `collectArtefacts`, because clearing is part of
    // collecting: a test that called the clearing function directly left the
    // call site free to be deleted with every test still passing.
    collectArtefacts(from, ["route-state-webkit"], into);

    // Replaced by this run's, not merely deleted.
    assert.equal(
      readFileSync(resolve(report, "route-state-webkit.json"), "utf8"),
      "this run",
    );
    assert.equal(
      existsSync(resolve(results, "a-case-route-state-webkit")),
      false,
    );
    // Playwright's own directory for the lane, where `.last-run.json` lands.
    assert.equal(existsSync(resolve(results, "route-state-webkit")), false);
    // Another lane's evidence is not this run's to delete. A host `--e2e` run
    // writes chromium results into the same directory.
    assert.equal(existsSync(resolve(report, "appearance-chromium.json")), true);
    assert.equal(
      existsSync(resolve(results, "a-case-appearance-chromium/trace.zip")),
      true,
    );
  });

  test("never writes through a link the container left in the checkout", (t) => {
    // A container running a thousand third-party install scripts chooses what
    // lands in the mount. Copying the tree recreated its symlinks here, and the
    // next run wrote *through* one — overwriting a file outside the repository
    // entirely. Proven end to end before this: the victim file's contents were
    // replaced.
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");
    const elsewhere = resolve(scratch(t, "webkit-victim-"), "victim.txt");

    writeFileSync(elsewhere, "ORIGINAL");

    const results = resolve(
      into,
      "apps/web/test-results/a-case-appearance-webkit",
    );

    mkdirSync(results, { recursive: true });
    symlinkSync(elsewhere, resolve(results, "trace.zip"));

    mkdirSync(resolve(from, "apps/web/test-results/a-case-appearance-webkit"), {
      recursive: true,
    });
    writeFileSync(
      resolve(from, "apps/web/test-results/a-case-appearance-webkit/trace.zip"),
      "FROM THE CONTAINER",
    );

    collectArtefacts(from, ["appearance-webkit"], into);

    assert.equal(readFileSync(elsewhere, "utf8"), "ORIGINAL");
  });

  test("copies no symlink the container put in the mount", (t) => {
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");
    const report = resolve(from, "apps/web/acceptance-report");

    mkdirSync(report, { recursive: true });
    writeFileSync(resolve(report, "appearance-webkit.json"), "{}");
    symlinkSync("/etc/hosts", resolve(report, "hosts.json"));

    const collected = collectArtefacts(from, ["appearance-webkit"], into);

    assert.equal(collected.length, 1);
    assert.equal(
      existsSync(resolve(into, "apps/web/acceptance-report/hosts.json")),
      false,
    );
  });

  test("keeps the previous run's evidence when this run produced none", (t) => {
    // A run that reached docker and died there — unpullable image, denied
    // mount, status 125 — used to delete the reports and traces and put
    // nothing in their place. That is the exact moment somebody is re-running
    // in order to look at them again.
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");
    const report = resolve(into, "apps/web/acceptance-report");

    mkdirSync(report, { recursive: true });
    writeFileSync(resolve(report, "route-state-webkit.json"), "the run before");

    const collected = collectArtefacts(from, ["route-state-webkit"], into);

    assert.deepEqual(collected, []);
    assert.equal(
      readFileSync(resolve(report, "route-state-webkit.json"), "utf8"),
      "the run before",
    );
  });

  test("says nothing was collected rather than inventing a report", (t) => {
    // A container that died during install writes no report. Reporting one
    // anyway — or failing here — would both be worse than saying so.
    const from = scratch(t, "webkit-out-");
    const into = scratch(t, "webkit-root-");

    assert.deepEqual(collectArtefacts(from, ["appearance-webkit"], into), []);
  });
});

describe("the docker invocation", () => {
  test("pins the image to the exact Playwright the repository installs", () => {
    // A version mismatch here is the whole bug this script routes around, in
    // the other direction. Asserting the shape let a bump pass silently, which
    // is the one way this script can go quietly wrong.
    const installed = JSON.parse(
      readFileSync(resolve(repositoryRoot, "package.json"), "utf8"),
    );
    const playwright =
      (installed.devDependencies ?? {})["@playwright/test"] ??
      (installed.dependencies ?? {})["@playwright/test"];

    assert.ok(playwright, "the workspace must depend on @playwright/test");
    assert.equal(
      PLAYWRIGHT_IMAGE,
      `mcr.microsoft.com/playwright:v${playwright.replace(/^[^\d]*/u, "")}-noble`,
    );
  });

  test("reads the tree from stdin and never mounts the checkout", () => {
    // node_modules built on macOS cannot be mounted into Linux — the native
    // binaries are for the wrong platform. The tree arrives as an archive and
    // the container installs for itself. One mount is allowed and it is empty:
    // the directory the reports are carried out in.
    const argv = dockerArguments({
      envFile: "/tmp/e.env",
      lanes: WEBKIT_LANES,
      outputDirectory: "/tmp/out",
    });

    assert.equal(argv[0], "run");
    assert.ok(argv.includes("--rm"));
    assert.ok(argv.includes("-i"));
    assert.ok(argv.includes("--env-file"));
    assert.ok(argv.includes("/tmp/e.env"));
    assert.ok(argv.includes(PLAYWRIGHT_IMAGE));

    const mounts = argv.filter((a) => a.includes(":/") && a.startsWith("/"));

    assert.deepEqual(mounts, [`/tmp/out:${CONTAINER_OUTPUT}`]);
    for (const mount of mounts) {
      assert.ok(
        !mount.startsWith(repositoryRoot),
        `${mount} mounts the checkout`,
      );
    }
  });

  test("exits with the lanes' own status, whatever the copying does", (t) => {
    // Pinned by running it, because matching strings in it did not pin it: an
    // ordering that reported a failing lane as a pass satisfied every
    // assertion the previous version made. These execute the script.
    const workspace = scratch(t, "webkit-script-");
    const bin = resolve(workspace, "bin");
    const readOnly = resolve(workspace, "read-only");

    mkdirSync(bin, { recursive: true });
    mkdirSync(readOnly, { recursive: true });

    const runWith = (laneExit, output) => {
      writeFileSync(resolve(bin, "node"), `#!/bin/sh\nexit ${laneExit}\n`, {
        mode: 0o755,
      });

      return spawnSync(
        "bash",
        [
          "-c",
          // `set -e` is on when this block begins: the container's script
          // enables it for the install. Running the block without it would
          // test a context that does not exist, and would miss a missing
          // `set +e` — under which a failing lane aborts before its status is
          // taken and the artefacts are never copied.
          `set -e\n${runAndCollectScript(["appearance-webkit"], output)}`,
        ],
        {
          cwd: workspace,
          encoding: "utf8",
          env: { ...process.env, PATH: `${bin}:${process.env.PATH}` },
        },
      ).status;
    };

    const writable = resolve(workspace, "out");

    // Something for the copy to find, so the assertions below are about the
    // copy happening rather than about an empty source.
    mkdirSync(resolve(workspace, "apps/web/acceptance-report"), {
      recursive: true,
    });
    writeFileSync(
      resolve(workspace, "apps/web/acceptance-report/a-lane.json"),
      "{}",
    );

    assert.equal(runWith(7, writable), 7, "a failing lane must fail the run");
    // The run whose artefacts matter most is the one that failed. Without
    // `set +e` the script aborts at the lane and copies nothing, and the exit
    // status alone cannot tell: it is the lane's either way.
    assert.equal(
      existsSync(resolve(writable, "apps/web/acceptance-report/a-lane.json")),
      true,
      "a failing lane must still yield its artefacts",
    );

    rmSync(writable, { force: true, recursive: true });
    assert.equal(runWith(0, writable), 0, "a passing lane must pass the run");

    // An unwritable mount is the real case: rootless docker, a userns-remapped
    // daemon, a denied share. `mkdir` aborted the script under `set -e` and
    // answered for the lanes — a passing lane reported as a failure, and a
    // failing one reported as the wrong failure.
    chmodSync(readOnly, 0o500);
    const denied = resolve(readOnly, "out");

    assert.equal(runWith(7, denied), 7, "a denied mount must not answer");
    assert.equal(runWith(0, denied), 0, "a denied mount must not fail a pass");
    chmodSync(readOnly, 0o700);
  });

  test("copies the artefacts after the lanes, never before", () => {
    const script = runAndCollectScript(WEBKIT_LANES);

    assert.ok(
      script.indexOf("run-foundation-e2e.mjs") < script.indexOf("code=$?"),
      "the lanes must run before their status is taken",
    );
    assert.ok(
      script.indexOf("code=$?") < script.indexOf("acceptance-report"),
      "the artefacts must be copied after the status is taken",
    );
    assert.match(script, /test-results/u);
  });

  test("carries a repeat into the container, or says nothing about one", () => {
    const once = runAndCollectScript(["route-state-webkit"]);
    const looped = runAndCollectScript(
      ["route-state-webkit"],
      CONTAINER_OUTPUT,
      12,
    );

    assert.equal(
      once.includes("--repeat-each"),
      false,
      "an ordinary run must ask for no repeat",
    );
    assert.match(
      looped,
      /run-foundation-e2e\.mjs route-state-webkit --repeat-each=12/u,
    );
  });

  test("a repeat reaches the script docker is handed", () => {
    const argv = dockerArguments({
      envFile: "/tmp/e.env",
      lanes: ["route-state-webkit"],
      repeatEach: 9,
    });

    assert.match(argv.at(-1), /--repeat-each=9/u);
  });

  test("lets the container reach the host's database stack", () => {
    const argv = dockerArguments({
      envFile: "/tmp/e.env",
      lanes: WEBKIT_LANES,
    });

    assert.ok(argv.includes("--add-host"));
    assert.ok(argv.some((a) => a.startsWith("host.docker.internal:")));
  });

  test("names the lanes it was given, and passes engine-strict off", () => {
    const argv = dockerArguments({
      envFile: "/tmp/e.env",
      lanes: WEBKIT_LANES,
    });
    const script = argv.at(-1);

    for (const lane of WEBKIT_LANES) assert.ok(script.includes(lane), lane);
    // The image ships a Node newer than this repository's engines range, and
    // the install refuses on that alone unless engine-strict is off.
    assert.match(script, /npm_config_engine_strict=false/u);
  });
});
