describe("the environment the container runs with", () => {
  test("carries no value from the checkout that is not needed", () => {
    // The container installs 1000-odd packages from the public registry and
    // runs their lifecycle scripts. Handing that the developer's whole
    // environment — every secret `.env.local` holds, and the shell's besides —
    // is not something this run needs, so it does not happen: the environment
    // is built from an allowlist, and everything else is simply absent.
    const env = containerEnvironment(A_REAL_CHECKOUT);

    for (const name of [
      "DATABASE_URL_UNPOOLED",
      "POSTGRES_URL",
      "POSTGRES_URL_NON_POOLING",
      "POSTGRES_PRISMA_URL",
      "PGHOST",
      "PGUSER",
      "PGPASSWORD",
      "PGDATABASE",
      ...HOSTED_VARIABLES,
      "VERCEL_OIDC_TOKEN",
    ]) {
      assert.equal(
        env[name],
        undefined,
        `${name} must not reach the container`,
      );
    }
  });

  test("keeps every real secret in the checkout out of the container", () => {
    // Nothing the lanes drive authenticates against GitHub or Resend: the
    // magic link is read from `/api/test/email-outbox`, not from an inbox. So
    // the schema's required names are satisfied with values minted here, and
    // the real ones never leave this machine.
    const env = containerEnvironment(A_REAL_CHECKOUT);

    for (const name of [
      "BETTER_AUTH_SECRET",
      "GITHUB_CLIENT_SECRET",
      "RESEND_API_KEY",
    ]) {
      assert.notEqual(
        env[name],
        A_REAL_CHECKOUT[name],
        `${name} must be minted here, not copied from the checkout`,
      );
      assert.ok(
        typeof env[name] === "string" && env[name].length > 0,
        `${name} must still be present, or the server refuses to start`,
      );
    }
  });

  test("mints an auth secret the schema accepts, different every run", () => {
    // `server-schema.ts` requires at least 32 characters. A fixed string would
    // do that and would also be a shared secret checked into a repository.
    const first = containerEnvironment(A_REAL_CHECKOUT).BETTER_AUTH_SECRET;
    const second = containerEnvironment(A_REAL_CHECKOUT).BETTER_AUTH_SECRET;

    assert.ok(first.length >= 32, first.length);
    assert.notEqual(first, second);
  });

  test("does not hand the container this machine's paths", () => {
    // PATH, HOME and TMPDIR name places that exist here and not in the image;
    // TMPDIR in particular breaks `mkdtemp` inside the container with ENOENT.
    // CI changes what Playwright forbids. None of them belong in the image.
    const env = containerEnvironment(A_REAL_CHECKOUT);

    for (const name of ["PATH", "HOME", "TMPDIR", "CI"]) {
      assert.equal(env[name], undefined, name);
    }
  });

  test("runs the application on pg, because the local stack declares no proxy", () => {
    // The WebSocket proxy left the local stack on 2026-09-28, so the hosted
    // driver has nothing to reach the local database through. pg dials the
    // connection string's own host, which is why that string is the one
    // judged below.
    const env = containerEnvironment(A_REAL_CHECKOUT);

    assert.equal(env.REQUESTPORT_DATABASE_DRIVER, "pg");
    for (const name of HOSTED_VARIABLES) assert.equal(env[name], undefined);
  });

  test("redirects an IPv6 loopback database at the host too", () => {
    // Inside a container 127.0.0.1 — and ::1 — is the container.
    // `clean-locally.mjs` accepts the bracketed spelling, so it is reachable.
    const env = containerEnvironment({
      ...A_REAL_CHECKOUT,
      REQUESTPORT_LOCAL_DATABASE_URL:
        "postgresql://requestport:pw@[::1]:55432/requestport_local",
    });

    assert.equal(
      env.DATABASE_URL,
      "postgresql://requestport:pw@host.docker.internal:55432/requestport_local",
    );
  });

  test("refuses to run without a local database named, rather than reaching for DATABASE_URL", () => {
    const { REQUESTPORT_LOCAL_DATABASE_URL: _omitted, ...unnamed } =
      A_REAL_CHECKOUT;

    assert.throws(
      () => containerEnvironment(unnamed),
      /REQUESTPORT_LOCAL_DATABASE_URL is not set/u,
    );
  });

  test("names the local database, never the one .env.local was pulled with", () => {
    const env = containerEnvironment(A_REAL_CHECKOUT);

    assert.equal(
      env.DATABASE_URL,
      "postgresql://requestport:pw@host.docker.internal:55432/requestport_local",
    );
    assert.equal(new URL(env.DATABASE_URL).hostname, "host.docker.internal");
  });

  test("refuses a local database that is not on this machine, however it is spelled", () => {
    // Now the string pg dials, so the one that decides where every query
    // lands. A prefix replacement once rewrote `127.0.0.1.evil.example` —
    // somebody else's machine — to `host.docker.internal.evil.example`.
    for (const url of [
      "postgresql://x:pw@ep-elsewhere.example.test/appdb",
      "postgresql://x:pw@127.0.0.1.evil.example:55432/requestport_local",
      "postgresql://x:pw@10.0.0.5:55432/requestport_local",
    ]) {
      assert.throws(
        () =>
          containerEnvironment({
            ...A_REAL_CHECKOUT,
            REQUESTPORT_LOCAL_DATABASE_URL: url,
          }),
        /not on this machine/u,
        url,
      );
    }
  });

  test("refuses a loopback string whose query names another host", () => {
    // Rewriting the authority to host.docker.internal leaves the query as it
    // was, and pg dials the query's `host` over the authority's. Measured
    // 2026-09-28: this string reached the container as
    // `…@host.docker.internal:55432/<database>?host=elsewhere.example.invalid`,
    // which pg resolves to elsewhere.example.invalid.
    assert.throws(
      () =>
        containerEnvironment({
          ...A_REAL_CHECKOUT,
          REQUESTPORT_LOCAL_DATABASE_URL:
            "postgresql://x:pw@127.0.0.1:55432/appdb?host=elsewhere.example.invalid",
        }),
      /query parameter/u,
    );
  });

  test("carries no Vercel identity into the container", () => {
    const env = containerEnvironment({
      ...A_REAL_CHECKOUT,
      VERCEL_ENV: "production",
      VERCEL_GIT_COMMIT_REF: "main",
    });

    assert.equal(env.VERCEL_ENV, undefined);
    assert.equal(env.VERCEL_GIT_COMMIT_REF, undefined);
    assert.equal(env.VERCEL_OIDC_TOKEN, undefined);
  });

  test("points the application at the server the lanes drive", () => {
    const env = containerEnvironment(A_REAL_CHECKOUT);

    assert.equal(env.BETTER_AUTH_URL, ACCEPTANCE_BASE_URL);
    assert.equal(env.NEXT_PUBLIC_APP_URL, ACCEPTANCE_BASE_URL);
  });
});

describe("the file docker reads the environment from", () => {
  test("writes values unquoted, because --env-file keeps quotes literally", (t) => {
    // A build inside the container died on LOG_LEVEL's enum for this reason.
    // That was the lucky version: every other value was wrong the same way.
    const path = writeEnvFile({ LOG_LEVEL: "info" }, scratch(t, "webkit-env-"));
    const body = readFileSync(path, "utf8");
    assert.match(body, /^LOG_LEVEL=info$/mu);
  });

  test("is readable only by the person who ran it", (t) => {
    const path = writeEnvFile({ LOG_LEVEL: "info" }, scratch(t, "webkit-env-"));
    const mode = statSync(path).mode & 0o777;
    assert.equal(mode, 0o600);
  });

  test("drops a value carrying a newline rather than writing half of it", (t) => {
    // `--env-file` reads a line at a time, so a value with a newline in it
    // becomes a variable whose name is the rest of that value.
    const path = writeEnvFile(
      { GOOD: "yes", BAD: "one\ntwo" },
      scratch(t, "webkit-env-"),
    );
    const body = readFileSync(path, "utf8");
    assert.match(body, /^GOOD=yes$/mu);
    assert.doesNotMatch(body, /two/u);
  });
});

describe("resolving the stack before the container starts", () => {
  test("probes the local database the way the gate does, and hands the container pg", () => {
    // Wrapping this script in `with-root-env` instead put the production guard
    // in front of a `DATABASE_URL` that still named staging, and it refused,
    // correctly. The local database is named, then probed where pg will dial.
    const probed = [];
    const env = prepareHostEnvironment(
      { REQUESTPORT_LOCAL_DATABASE_URL: LOCAL_DATABASE },
      (url) => {
        probed.push(url);
        return true;
      },
    );

    assert.deepEqual(probed, [LOCAL_DATABASE]);
    assert.equal(env.REQUESTPORT_DATABASE_DRIVER, "pg");
    for (const name of HOSTED_VARIABLES) assert.equal(env[name], undefined);
    assert.match(env.DATABASE_URL, /host\.docker\.internal:55432/u);
  });

  test("says the stack is down rather than asking anybody to approve staging", () => {
    // Matching on the `docker compose up -d` line alone could not tell this
    // refusal from another that carries it, so it matches what only this one
    // says.
    assert.throws(
      () =>
        prepareHostEnvironment(
          { REQUESTPORT_LOCAL_DATABASE_URL: LOCAL_DATABASE },
          () => false,
        ),
      /The local database stack is not running/u,
    );
  });

  test("refuses a local database pg could not authenticate to, before the container starts", () => {
    // pg refuses to fill a missing user or password from PG* variables, so the
    // server in the container would fail on its first query, ten minutes in.
    assert.throws(
      () =>
        prepareHostEnvironment(
          {
            REQUESTPORT_LOCAL_DATABASE_URL:
              "postgresql://requestport@127.0.0.1:55432/requestport_local",
          },
          () => {
            throw new Error("nothing may be probed for a string pg refuses");
          },
        ),
      /user or no password/u,
    );
  });

  test("refuses a string whose query would redirect pg, before probing anything", () => {
    assert.throws(
      () =>
        prepareHostEnvironment(
          {
            REQUESTPORT_LOCAL_DATABASE_URL:
              "postgresql://x:pw@127.0.0.1:55432/appdb?host=elsewhere.example.invalid",
          },
          () => {
            throw new Error("nothing may be probed for a string pg redirects");
          },
        ),
      /query parameter/u,
    );
  });
});

describe("the signing material the minted secret cannot read", () => {
  test("clears only the jwks table, and only in the local container", () => {
    // Better Auth encrypts its JWKS private key with BETTER_AUTH_SECRET and
    // stores it in the database. The local database outlives a run, so a key
    // written under one secret cannot be read under the next — which failed
    // the case that issues an authorization code, with "Failed to decrypt
    // private key". Clearing it makes the server mint a fresh one. It is
    // signing material for a disposable local database and nothing else.
    const calls = [];
    const spawn = (command, argv) => {
      calls.push({ command, argv });
      return { status: 0 };
    };

    assert.equal(clearStaleJwks(LOCAL_DATABASE, spawn), true);
    assert.equal(calls.length, 1);
    assert.equal(calls[0].command, "docker");
    assert.ok(calls[0].argv.includes("requestport-local-db"));
    assert.ok(calls[0].argv.includes(JWKS_RESET_STATEMENT));
    assert.match(JWKS_RESET_STATEMENT, /^delete from "jwks";$/u);
    // Nothing else may be swept along: the lanes' own rows are the evidence a
    // failure is read from, and dropping a schema here would hide a migration
    // that never ran.
    assert.doesNotMatch(JWKS_RESET_STATEMENT, /drop|truncate|schema/iu);
  });

  test("reports a failure rather than running the lanes against a broken key", () => {
    assert.equal(
      clearStaleJwks(LOCAL_DATABASE, () => ({
        status: 1,
        stderr: "no such container",
      })),
      false,
    );
  });

  test("clears the jwks of the database the lanes run against, and no other (Plan 13, X20)", () => {
    // The container's lanes run against the database REQUESTPORT_LOCAL_DATABASE_URL
    // names — a track worktree's own. Until X20 the clear named
    // `requestport_local` whatever the URL said, so from a track it deleted
    // the main checkout's keys and left the track's: the container could not
    // read the key the host lanes had minted, and the host lanes could not
    // read the one the container minted.
    const calls = [];
    const spawn = (command, argv) => {
      calls.push({ command, argv });
      return { status: 0 };
    };

    assert.equal(
      clearStaleJwks(
        "postgresql://requestport:pw@127.0.0.1:55432/rp_track_x",
        spawn,
      ),
      true,
    );
    const argv = calls[0].argv;
    assert.equal(argv[argv.indexOf("-d") + 1], "rp_track_x");
    assert.equal(argv.includes("requestport_local"), false);
  });
});

