/*
  The queries in packages/db that run against a tenant-owned table without
  that table's organisation predicate, and the reason each may.

  Read by tenant-scope-sweep.test.ts, which fails on a query missing from this
  list, on a count that no longer matches, and on an entry that no longer
  occurs. It is a record of what the application's own checks rest on today,
  not a claim that each is safe for ever: a query here is exactly where
  row-level security (Plan 13, track I.2) has to hold the line instead.

  `file` is relative to packages/db/src. `fn` is the dotted path of the
  named functions enclosing the query, or `<module>` at the top level; a
  helper's query checked once per call reads `caller → helper`. `table` is
  the schema export of the first unscoped source; the tables joined to it
  ride on it and are named in the sweep's message, not here. `count` is the
  number of such queries in that function against that table.

  `kind`:
  - worker: a background task that works across every organisation by
    design, and carries each row's organisation forward from the row;
  - maintenance: a whole-database job that returns counts or acts on ids it
    chose itself (integrity check, metrics, retention, key rotation);
  - credential: finds the organisation from a presented secret or one-time
    value, so the organisation is the answer, not an input;
  - identity: keyed by a global identity (a user and an OAuth client, an
    e-mail address, a unique slug);
  - member-scoped: spans every organisation the signed-in user belongs to;
  - verified-earlier: keyed by an id the same function or transaction has
    already read with its organisation predicate, refusing when it was absent;
  - caller-verified: a repository port that takes a bare id, whose callers in
    packages/domain pass one they loaded with the organisation predicate;
  - test-support: code under src/test-support, or testing.ts (the
    `@requestport/db/testing` subpath), that only test code imports, never
    the product.

  A `table` of `?` is a shape the sweep reports without reading (see the
  test's header), charged to no table.
*/

